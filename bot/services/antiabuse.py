"""
Пробный период -- один на устройство, а не на аккаунт Telegram.

ЗАЧЕМ
Аккаунт в Telegram заводится за минуту. Если пробный период считать по
идентификатору аккаунта, любой желающий получает его заново сколько угодно
раз: закончился -- завёл новый аккаунт, открыл приложение, снова четырнадцать
дней бесплатно. Платить в такой схеме будут только те, кому лень.

КАК
Приложение при первом запуске выписывает себе случайный идентификатор
устройства и хранит его на самом устройстве. Дополнительно считается грубый
отпечаток: часовой пояс, язык, разрешение экрана, платформа. Ни то, ни другое
не опознаёт человека -- это признак устройства, а не личности.

Правило одно: пробный период принадлежит тому аккаунту, который на этом
устройстве появился первым. Второй и следующий аккаунты пробного не получают
и сразу видят кнопку оплаты. Их при этом ничего не блокирует: бесплатный тариф
со всеми расчётами, картой и справочниками остаётся доступен.

ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ
  * Блокировки по адресу в сети. На судне весь экипаж выходит через один
    спутниковый канал, и по адресу пришлось бы отказать всем, кроме первого.
    Это не борьба со злоупотреблением, а наказание нормальных людей.
  * Жёсткой блокировки аккаунта. Максимум -- отказ в повторном пробном.
  * Скрытого отпечатка браузера с canvas и шрифтами. Он точнее, но это уже
    слежка за человеком, а задача -- всего лишь не выдавать пробный дважды.

ЧЕСТНО О ПРЕДЕЛАХ
Обойти можно: очистить память приложения, взять другой телефон, открыть в
другом браузере. Полностью закрыть это нельзя ничем, кроме привязки к
платёжным данным или к документу, а такой ценой -- не нужно. Задача не
запереть намертво, а сделать обход заметно менее удобным, чем оплата, и
показать владельцу, где это происходит.
"""
from __future__ import annotations

import hashlib
import logging
import re

logger = logging.getLogger(__name__)

_ID_RE = re.compile(r"^[A-Za-z0-9_-]{8,64}$")


def clean_device_id(raw: str) -> str:
    """Идентификатор устройства из запроса. Мусор отбрасываем: он приходит
    от клиента, а значит, может быть каким угодно."""
    raw = (raw or "").strip()
    return raw if _ID_RE.match(raw) else ""


def fingerprint(raw: str) -> str:
    """Короткий хеш от признаков устройства.

    Хешируем, а не храним как есть: в базе не нужны ни разрешение экрана,
    ни часовой пояс конкретного человека -- достаточно уметь сравнить
    два устройства между собой."""
    raw = (raw or "").strip()
    if len(raw) < 4:
        return ""
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()[:32]


def register(db, user_id: int, device_id: str, fp_raw: str) -> None:
    """Запомнить, что этот аккаунт заходил с этого устройства."""
    dev = clean_device_id(device_id)
    if not dev or not user_id:
        return
    try:
        db.touch_device(dev, user_id, fingerprint(fp_raw))
    except Exception:
        logger.exception("Не удалось записать устройство")


def trial_allowed(db, user_id: int, device_id: str, fp_raw: str) -> tuple[bool, str]:
    """Положен ли этому аккаунту пробный период.

    Возвращает (можно, причина отказа). Когда устройство неизвестно --
    разрешаем: приложение могли открыть со старой версии, из другого
    браузера или с отключённым хранилищем, и отказывать на таком основании
    нельзя."""
    dev = clean_device_id(device_id)
    if not dev:
        return True, ""

    try:
        first = db.device_owner(dev)
        if first is not None and first != user_id:
            return False, "device"

        fp = fingerprint(fp_raw)
        if fp:
            first_fp = db.fingerprint_owner(fp)
            if first_fp is not None and first_fp != user_id:
                return False, "fingerprint"
    except Exception:
        logger.exception("Проверка устройства не удалась")
        return True, ""

    return True, ""


