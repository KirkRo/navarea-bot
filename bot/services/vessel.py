def flag_by_mmsi(mmsi: str | None) -> str | None:
    """Страна регистрации по первым трём цифрам MMSI (код MID)."""
    if not mmsi:
        return None
    digits = "".join(ch for ch in str(mmsi) if ch.isdigit())
    if len(digits) < 3:
        return None
    return MID.get(digits[:3])


