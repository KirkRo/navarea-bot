def flag_by_mmsi(mmsi: str | None) -> str | None:
    """Страна регистрации по первым трём цифрам MMSI (код MID)."""
    if not mmsi:
        return None
    digits = "".join(ch for ch in str(mmsi) if ch.isdigit())
    if len(digits) < 3:
        return None
    return MID.get(digits[:3])


def normalize(data: dict) -> dict:
    """Оставляет только известные поля и подставляет флаг по MMSI."""
    clean = {k: str(v).strip() for k, v in (data or {}).items()
             if k in FIELD_KEYS and str(v).strip()}
    if not clean.get("flag"):
        f = flag_by_mmsi(clean.get("mmsi"))
        if f:
            clean["flag"] = f
    return clean


def prefill_for(tool_id: str, vessel: dict) -> dict:
    """Что подставить в поля расчёта из карточки судна."""
    mapping = CALC_PREFILL.get(tool_id) or {}
    out = {}
    for field_key, vessel_key in mapping.items():
        if vessel_key and vessel.get(vessel_key):
            out[field_key] = vessel[vessel_key]
    return out


def vessel_payload(vessels: list[dict], active_id: str | None, docs: list[dict],
                   provider_info: dict) -> dict:
    active = next((v for v in vessels if v.get("_id") == active_id), None)
    if active is None and vessels:
        active = vessels[0]
    return {
        "sections": SECTIONS,
        "doc_types": DOC_TYPES,
        "vessels": vessels,
        "active": active or {},
        "active_id": (active or {}).get("_id"),
        "docs": docs,
        "prefill": {tid: prefill_for(tid, active or {}) for tid in CALC_PREFILL},
        "provider": provider_info,
        "note": ("Данные судна хранятся только у тебя и подставляются в расчёты. "
                 "Автоматический поиск по названию требует доступа к AIS-сервису."),
    }
