def chokepoint_notes(titles) -> list[dict]:
    """Замечания по проливам и каналам, через которые проходит маршрут."""
    out = []
    for t in titles or []:
        note = CHOKEPOINTS.get(t)
        if note:
            out.append({"point": t, "note": note})
    return out


def _key(a: str, b: str) -> tuple[str, str] | None:
    if (a, b) in PASSAGES:
        return (a, b)
    if (b, a) in PASSAGES:
        return (b, a)
    return None


def passage_note(lat1: float, lon1: float, lat2: float, lon2: float,
                 via=None) -> dict:
    """Что NP136 говорит про переход между двумя точками.

    via -- названия проливов и каналов из проложенного маршрута. По ним
    замечания находятся даже там, где статьи по паре районов нет: путь
    из Чёрного моря куда угодно всё равно идёт Босфором, и сказать про
    течение в проливе полезнее, чем промолчать."""
    r1 = region_of(lat1, lon1)
    r2 = region_of(lat2, lon2)
    out = {
        "source": SOURCE,
        "from_region": r1[1] if r1 else None,
        "to_region": r2[1] if r2 else None,
        "chokepoints": chokepoint_notes(via),
        "disclaimer": ("Справка по NP136. Планирование перехода выполняется по самому "
                       "изданию, картам и Sailing Directions."),
    }

    k = _key(r1[0], r2[0]) if (r1 and r2) else None
    if k:
        out.update(PASSAGES[k])
        return out

    if r1 and r2 and r1[0] == r2[0]:
        out["note"] = ("Переход внутри одного района: отдельной океанской статьи NP136 "
                       "не даёт, смотри описание района и проливов.")
    elif not r1 or not r2:
        out["note"] = "Район не распознан, отдельной статьи нет."
    else:
        out["note"] = ("Прямой статьи по этой паре районов в подборке нет. "
                       "Смотри NP136 по районам отправления и прибытия.")

    if not out["chokepoints"]:
        return out
    out["note"] += " Ниже -- замечания по проливам и каналам на этом пути."
    return out


