def days_left(expires_iso: str) -> int | None:
    """Сколько дней осталось. Отрицательное -- просрочен."""
    try:
        d = date.fromisoformat(str(expires_iso)[:10])
    except (ValueError, TypeError):
        return None
    return (d - datetime.now(timezone.utc).date()).days


def cert_status(expires_iso: str) -> str:
    d = days_left(expires_iso)
    if d is None:
        return "unknown"
    if d < 0:
        return "expired"
    if d <= 30:
        return "soon"
    if d <= 90:
        return "watch"
    return "ok"


def due_threshold(expires_iso: str, already_notified: str) -> tuple[int, str] | None:
    """Какой порог напоминания сейчас наступил и ещё не отправлялся.

    Берётся БЛИЖАЙШИЙ подходящий порог, а не первый попавшийся: если до
    истечения 5 дней, человеку нужно напоминание «осталась неделя», а не
    «осталось 60 дней». Иначе при добавлении сертификата с коротким сроком
    приходило бы сообщение с уже неактуальной цифрой."""
    d = days_left(expires_iso)
    if d is None or d < 0:
        return None
    done = set((already_notified or "").split(","))
    for days, label in sorted(CERT_THRESHOLDS):  # от самого срочного к дальнему
        if d <= days:
            return None if str(days) in done else (days, label)
    return None


